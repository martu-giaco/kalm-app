    <script>
        (function () {
            const checkbox = document.getElementById('termsCheck');
            const button = document.getElementById('acceptBtn');

            function setEnabledState() {
                button.disabled = false;
                button.classList.remove(
                    'bg-[#CCE2E5]',
                    'text-[#2A4043]',
                    'cursor-not-allowed',
                    'opacity-50'
                );
                button.classList.add(
                    'bg-[#2A4043]',
                    'text-white',
                    'cursor-pointer',
                    'opacity-100'
                );
            }

            function setDisabledState() {
                button.disabled = true;
                button.classList.remove(
                    'bg-[#2A4043]',
                    'text-white',
                    'cursor-pointer',
                    'opacity-100'
                );
                button.classList.add(
                    'bg-[#CCE2E5]',
                    'text-[#2A4043]',
                    'cursor-not-allowed',
                    'opacity-50'
                );
            }

            // Estado inicial
            checkbox.checked ? setEnabledState() : setDisabledState();

            checkbox.addEventListener('change', function () {
                this.checked ? setEnabledState() : setDisabledState();
            });

            // Prevención adicional
            document.getElementById('termsForm').addEventListener('submit', function (e) {
                if (! checkbox.checked) {
                    e.preventDefault();
                    alert('Debes aceptar los Términos y Condiciones para completar el registro.');
                }
            });
        })();
    </script>
